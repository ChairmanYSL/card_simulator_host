"""Generate the two throwaway mock variants required by the plan.

* mock_android_silent.py  (plan section 4.7): a connected card that never acks
  card_config, to force `card_config_ack_timeout`.
* mock_pos_dup.py         (plan section 5.2): reports the SAME transaction_result
  frame twice (same msg_id) to exercise D2 duplicate handling.

Both are produced by textually transforming the repository mock, and every
substitution is asserted, so the variants cannot silently drift from the
originals.  The originals in tools/mock_clients/ are never modified.
"""

from __future__ import annotations

import sys
from pathlib import Path

REPO = Path(r"E:\Work\ZT\card_simulator_host")
MOCKS = REPO / "tools" / "mock_clients"
OUT = REPO / "tmp" / "v12test" / "scratch"

HEADER = "# GENERATED by make_mocks.py from {src} - throwaway test scaffolding.\n"


def make_silent() -> Path:
    src = MOCKS / "mock_android.py"
    text = src.read_text(encoding="utf-8")
    old = ("    if msg_type == MSG_CONFIG_PUSH:\n"
           "        await client.send_ack(msg_id)\n"
           "        config_type = frame.get(\"config_type\")\n")
    new = ("    if msg_type == MSG_CONFIG_PUSH:\n"
           "        # SILENT VARIANT: the ack is deliberately removed so the host\n"
           "        # hits card_config_ack_timeout (test plan section 4.7).\n"
           "        config_type = frame.get(\"config_type\")\n")
    if text.count(old) != 1:
        raise SystemExit(f"silent: anchor not found exactly once "
                         f"(count={text.count(old)})")
    text = text.replace(old, new)
    out = OUT / "mock_android_silent.py"
    out.write_text(HEADER.format(src=src.name) + text, encoding="utf-8")
    return out


def make_dup() -> Path:
    src = MOCKS / "mock_pos.py"
    text = src.read_text(encoding="utf-8")
    old = """    ack = await client.send_and_wait_ack(make_frame(
        MSG_TRANSACTION_RESULT,
        case_id=case_id,
        attempt_id=attempt_id,
        device_id=client.device_id,
        result=result,
    ))
    if ack is None:
        client.log("WARNING: no ack for transaction_result (not persisted?)")
"""
    new = """    dup_frame = make_frame(
        MSG_TRANSACTION_RESULT,
        case_id=case_id,
        attempt_id=attempt_id,
        device_id=client.device_id,
        result=result,
    )
    # RESEND VARIANT (test plan section 5.2): the identical frame, same msg_id,
    # is sent a second time to exercise host-side D2 dedup.
    ack = await client.send_and_wait_ack(dup_frame)
    if ack is None:
        client.log("WARNING: no ack for transaction_result (not persisted?)")
    client.log(f"RESEND#1 detail={ack.get('detail') if ack else None}")
    ack2 = await client.send_and_wait_ack(dup_frame)
    client.log(f"RESEND#2 detail={ack2.get('detail') if ack2 else None}")
"""
    if text.count(old) != 1:
        raise SystemExit(f"dup: anchor not found exactly once "
                         f"(count={text.count(old)})")
    text = text.replace(old, new)
    out = OUT / "mock_pos_dup.py"
    out.write_text(HEADER.format(src=src.name) + text, encoding="utf-8")
    return out


def make_reject_kernel() -> Path:
    """POS variant that acks pos_kernel_config with ok=false.

    Needed because the stock mock always acks ok=true, so the host's
    `pos_kernel_config_apply_failed` branch (executor.py:760) cannot be reached
    with it.  The plan's section 6.5 failure test expects that failure_reason;
    this variant is what actually exercises it.
    """
    src = MOCKS / "mock_pos.py"
    text = src.read_text(encoding="utf-8")
    old = """        for entry in (params.get("aid") or [])[:3]:
            client.log(f"  aid  {entry[:24]}…")
        await client.send_ack(frame.get("msg_id", ""))
        return
"""
    new = """        for entry in (params.get("aid") or [])[:3]:
            client.log(f"  aid  {entry[:24]}…")
        # REJECT VARIANT (test plan section 6.5 failure test): refuse the push
        # with ok=false so the host takes the apply-failed branch.
        client.log("REJECT VARIANT: acking pos_kernel_config with ok=false")
        await client.send(make_frame(
            MSG_ACK, ack_msg_id=frame.get("msg_id", ""), ok=False,
            detail="reject variant: simulated kernel apply failure"))
        return
"""
    if text.count(old) != 1:
        raise SystemExit(f"reject: anchor not found exactly once "
                         f"(count={text.count(old)})")
    text = text.replace(old, new)
    # the variant needs MSG_ACK, which the stock mock never uses
    imp_old = "    MSG_CASE_STARTED,\n"
    if text.count(imp_old) != 1:
        raise SystemExit("reject: import anchor not found exactly once")
    text = text.replace(imp_old, "    MSG_ACK,\n    MSG_CASE_STARTED,\n")
    out = OUT / "mock_pos_reject_kernel.py"
    out.write_text(HEADER.format(src=src.name) + text, encoding="utf-8")
    return out


if __name__ == "__main__":
    a = make_silent()
    b = make_dup()
    c = make_reject_kernel()
    print(f"wrote {a} ({a.stat().st_size} bytes)")
    print(f"wrote {b} ({b.stat().st_size} bytes)")
    print(f"wrote {c} ({c.stat().st_size} bytes)")
    # sanity: the silent variant must NOT ack config_push any more
    sa = a.read_text(encoding="utf-8")
    idx = sa.index("if msg_type == MSG_CONFIG_PUSH:")
    print("--- silent variant, config_push branch ---")
    print("\n".join(sa[idx:idx + 260].splitlines()[:6]))
    sb = b.read_text(encoding="utf-8")
    print("--- dup variant: RESEND present:",
          "RESEND#2" in sb, "send_and_wait_ack count:",
          sb.count("send_and_wait_ack"))
    sys.exit(0)
